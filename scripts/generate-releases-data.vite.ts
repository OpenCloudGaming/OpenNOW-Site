import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(rootDir, 'src/lib/releases.gen.ts');
const API = 'https://api.github.com/repos/OpenCloudGaming/OpenNOW';

type GitHubRelease = { tag_name: string; html_url: string; published_at: string | null; prerelease: boolean };
type ReleaseInfo = { tag: string; url: string; date: string | null };

async function getJson<T>(url: string): Promise<T> {
  const headers: Record<string, string> = { Accept: 'application/vnd.github+json', 'User-Agent': 'opennow-site-build' };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const response = await fetch(url, { headers, signal: AbortSignal.timeout(15_000) });
  if (!response.ok) throw new Error(`${url} → HTTP ${response.status}`);
  return (await response.json()) as T;
}

function toInfo(release: GitHubRelease): ReleaseInfo {
  return { tag: release.tag_name, url: release.html_url, date: release.published_at?.slice(0, 10) ?? null };
}

async function lookup(channel: string, load: () => Promise<GitHubRelease | undefined>): Promise<ReleaseInfo | null> {
  try {
    const release = await load();
    if (!release) throw new Error('no matching release');
    return toInfo(release);
  } catch (error) {
    console.warn(`[releases] ${channel} lookup failed, the status bar will omit it: ${(error as Error).message}`);
    return null;
  }
}

// Same channel rules as src/components/desktop-downloads.tsx.
const [stable, nightly] = await Promise.all([
  lookup('stable', () => getJson<GitHubRelease>(`${API}/releases/latest`)),
  lookup('nightly', async () =>
    (await getJson<GitHubRelease[]>(`${API}/releases?per_page=20`)).find(
      (release) => release.prerelease && release.tag_name.includes('nightly'),
    ),
  ),
]);

const content = `// @generated by scripts/generate-releases-data.vite.ts at build time — do not edit
export type ReleaseInfo = { tag: string; url: string; date: string | null };

export const releases: { stable: ReleaseInfo | null; nightly: ReleaseInfo | null } = ${JSON.stringify({ stable, nightly }, null, 2)};
`;

await writeFile(outputPath, content, 'utf-8');
console.log(`[releases] stable=${stable?.tag ?? 'none'} nightly=${nightly?.tag ?? 'none'}`);
